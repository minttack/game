"""IRL original-forest source and collision preflight.

Only operates on the dedicated /Game/IRL/Visual/ProceduralStarter
StaticMesh imported by the ONE authoritative IRL Unreal project.
No rewriting player maps, no fallback to guessed collision.
"""
import hashlib
import json
from pathlib import Path

ORIGINAL_ASSET_PATH = "/Game/IRL/Visual/ProceduralStarter"
REQUIRED_FILES = tuple(
    f"T_{name}_{kind}.png"
    for name in ("ForestSoil", "Granite", "LeafGreen")
    for kind in ("BaseColor", "Normal", "Roughness", "Height")
) + (
    "SM_IRL_TerrainPatch.obj",
    "SM_IRL_GraniteBoulder.obj",
    "SM_IRL_GrassClump.obj",
    "IRL_Original_PBR_Preview.png",
)
MANIFEST_NAME = "IRL_Original_PBR_Manifest.json"


def verify_source_manifest(source_dir):
    folder = Path(source_dir)
    manifest_file = folder / MANIFEST_NAME
    if not manifest_file.is_file():
        raise RuntimeError(f"IRL original material manifest absent: {manifest_file}")
    try:
        manifest = json.loads(manifest_file.read_text(encoding="utf8"))
    except (OSError, ValueError) as exc:
        raise RuntimeError("IRL original material manifest invalid") from exc
    listed = manifest.get("sha256")
    if not isinstance(listed, dict) or set(listed) != set(REQUIRED_FILES):
        raise RuntimeError("IRL original material manifest lacks expected 16 source assets")
    if manifest.get("asset_origin") != "Generated by original procedural source; NOT copied from any AAA title":
        raise RuntimeError("IRL original material source attribution invalid")
    if manifest.get("texture_packs") != ["ForestSoil","Granite","LeafGreen"]:
        raise RuntimeError("IRL original source pack names mismatch")
    for name in REQUIRED_FILES:
        expected = listed[name]
        if not isinstance(expected, str) or len(expected) != 64:
            raise RuntimeError("Missing/invalid IRL SHA-256 for " + name)
        p = folder / name
        if not p.is_file():
            raise RuntimeError("IRL source missing " + name)
        got = hashlib.sha256(p.read_bytes()).hexdigest()
        if got != expected.lower():
            raise RuntimeError("IRL source checksum mismatch: " + name)
    return len(REQUIRED_FILES)


def ensure_imported_ground_collision(unreal, mesh, mesh_asset_path, save_asset):
    """Configure static source mesh for walkable per-triangle static collision.

    Returns True only after read-back. Do not use ComplexAsSimple for dynamic
    bodies, or extrapolate this 80m test-tile choice to planetary collision.
    """
    if mesh_asset_path != ORIGINAL_ASSET_PATH + "/SM_IRL_TerrainPatch":
        raise RuntimeError("Refusing collision changes outside IRL generated ground asset")
    if mesh is None:
        raise RuntimeError("Original IRL terrain mesh not imported")
    if not hasattr(unreal, "CollisionTraceFlag"):
        raise RuntimeError("UE CollisionTraceFlag unavailable; no verified ground setup")
    desired = unreal.CollisionTraceFlag.CTF_USE_COMPLEX_AS_SIMPLE
    body = mesh.get_editor_property("body_setup")
    if body is None:
        raise RuntimeError("Imported terrain has no BodySetup; collision must be rebuilt in Unreal")
    if body.get_editor_property("collision_trace_flag") != desired:
        body.set_editor_property("collision_trace_flag", desired)
        save_asset(mesh)
    if body.get_editor_property("collision_trace_flag") != desired:
        raise RuntimeError("Terrain collision flag did not survive readback")
    return True


def require_walkable_terrain_component(unreal, actor):
    component = actor.get_component_by_class(unreal.StaticMeshComponent)
    if component is None:
        raise RuntimeError("Original terrain actor has no static mesh component")
    component.set_collision_profile_name("BlockAll")
    # Recheck that settings persisted on the actual component, not merely
    # on an imported asset; this remains an editor contract, not a gameplay test.
    if str(component.get_collision_profile_name()) != "BlockAll":
        raise RuntimeError("IRL ground actor did not retain blocking collision profile")
    return component
